"""Pydantic response schemas for factory data, time series, anomalies, and overview.

All monetary values are raw numeric floats (INR), energy in kWh, power in kW,
and timestamps in ISO 8601 strings.
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field
from app.data.factory_config import (
    BatteryConfig,
    BiomassConfig,
    GridConfig,
    ProductionZoneConfig,
    ShiftSchedule,
    SolarConfig,
    WindConfig,
)


class SimulationMetadata(BaseModel):
    is_synthetic: bool = Field(
        default=True,
        description="Explicit flag indicating data is simulated, not measured telemetry.",
    )
    simulation_seed: int = Field(default=42, description="Random seed used for deterministic generation.")
    simulation_date: str = Field(default="2026-10-14", description="Simulated 24-hour observation date.")
    disclaimer: str = Field(
        default=(
            "This dataset is synthetically generated for prototyping and algorithm evaluation. "
            "It does not represent measured SCADA or smart meter telemetry from any actual facility."
        )
    )


class MachineReading(BaseModel):
    machine_id: str
    name: str
    power_kw: float = Field(..., description="Simulated power consumption in kW.")
    energy_kwh: float = Field(..., description="Simulated energy consumption for interval in kWh.")
    is_active: bool = Field(..., description="Whether machine was active in production.")


class ZoneReading(BaseModel):
    zone_id: str
    zone_name: str
    power_kw: float = Field(..., description="Aggregate zone power in kW.")
    energy_kwh: float = Field(..., description="Aggregate zone energy in kWh.")
    production_units: float = Field(..., description="Simulated production units generated by zone.")
    is_active: bool = Field(..., description="Whether zone was actively running.")
    machines: List[MachineReading]


class GenerationAvailability(BaseModel):
    solar_power_kw: float = Field(..., ge=0.0, description="Available solar generation power in kW.")
    solar_energy_kwh: float = Field(..., ge=0.0, description="Available solar energy in kWh.")
    wind_power_kw: float = Field(..., ge=0.0, description="Available wind generation power in kW.")
    wind_energy_kwh: float = Field(..., ge=0.0, description="Available wind energy in kWh.")
    biomass_max_power_kw: float = Field(..., ge=0.0, description="Maximum dispatchable biomass power in kW.")
    biomass_max_energy_kwh: float = Field(..., ge=0.0, description="Maximum dispatchable biomass energy in kWh.")
    total_renewable_available_kwh: float = Field(..., ge=0.0, description="Sum of available renewable energy in kWh.")


class GridData(BaseModel):
    tariff_rate_inr_per_kwh: float = Field(..., ge=0.0, description="Active ToD electricity tariff in INR/kWh.")
    tariff_period_name: str = Field(..., description="Period label (Off-Peak, Normal, Peak).")
    supply_capacity_kw: float = Field(..., gt=0.0, description="Grid sanctioned contract demand in kW.")
    is_peak_tariff_period: bool = Field(..., description="Whether interval falls in peak tariff window.")


class IntervalMetadata(BaseModel):
    shift_name: str
    is_production_active: bool
    active_anomaly_ids: List[str] = Field(default_factory=list)


class TimeSeriesInterval(BaseModel):
    interval_index: int = Field(..., ge=0, le=23, description="Hour index (0 to 23).")
    timestamp: str = Field(..., description="ISO 8601 timestamp in local IST (+05:30).")
    interval_duration_hours: float = Field(default=1.0, description="Duration of this interval in hours.")
    production_demand_units: float = Field(..., ge=0.0, description="Scheduled target production units.")
    actual_production_output_units: float = Field(..., ge=0.0, description="Actual simulated production output.")
    total_factory_demand_kw: float = Field(..., ge=0.0, description="Total instantaneous factory demand in kW.")
    total_factory_energy_demand_kwh: float = Field(..., ge=0.0, description="Total energy demand for interval in kWh.")
    facility_baseload_kwh: float = Field(..., ge=0.0, description="Non-production facility baseload in kWh.")
    zones: List[ZoneReading]
    generation: GenerationAvailability
    grid: GridData
    metadata: IntervalMetadata


class FactoryTimeSeriesResponse(BaseModel):
    factory_id: str
    factory_name: str
    simulation_date: str
    total_intervals: int
    intervals: List[TimeSeriesInterval]
    simulation_metadata: SimulationMetadata


class AnomalyScenario(BaseModel):
    scenario_id: str = Field(..., description="Unique scenario identifier.")
    category: str = Field(..., description="Classification category of the anomaly.")
    title: str = Field(..., description="Human-readable title.")
    interval_index: int = Field(..., ge=0, le=23, description="Affected hour index (0 to 23).")
    timestamp: str = Field(..., description="ISO 8601 timestamp of affected interval.")
    affected_zone_id: Optional[str] = None
    affected_machine_id: Optional[str] = None
    expected_baseline_value: float = Field(..., description="Expected baseline value under normal conditions.")
    observed_simulated_value: float = Field(..., description="Actual simulated value with anomaly.")
    unit: str = Field(..., description="Physical unit of the baseline and observed values.")
    difference_value: float = Field(..., description="Observed minus expected difference.")
    severity: str = Field(..., description="Suggested severity: low, medium, high, critical.")
    reason: str = Field(..., description="Technical engineering diagnosis of why this occurred.")
    suggested_remediation: str = Field(..., description="Suggested operational corrective action.")


class AnomalyScenariosResponse(BaseModel):
    total_anomalies: int
    scenarios: List[AnomalyScenario]
    simulation_metadata: SimulationMetadata


class FactoryProfileResponse(BaseModel):
    factory_id: str
    name: str
    sector: str
    location: str
    currency: str
    power_unit: str
    energy_unit: str
    production_unit: str
    total_rated_connected_power_kw: float
    facility_baseload_kw: float
    zones: List[ProductionZoneConfig]
    shifts: List[ShiftSchedule]
    solar: SolarConfig
    wind: WindConfig
    biomass: BiomassConfig
    grid: GridConfig
    battery: BatteryConfig
    simulation_metadata: SimulationMetadata


class DemandIntervalSummary(BaseModel):
    interval_index: int
    timestamp: str
    demand_kw: float
    demand_kwh: float
    grid_tariff_inr_per_kwh: float


class RenewableAvailabilitySummary(BaseModel):
    solar_total_kwh: float
    wind_total_kwh: float
    biomass_available_total_kwh: float
    total_renewable_available_kwh: float


class FactoryOverviewResponse(BaseModel):
    factory_id: str
    factory_name: str
    simulation_date: str
    total_intervals: int
    total_factory_energy_demand_kwh: float
    total_production_units: float
    average_energy_intensity_kwh_per_unit: float
    renewable_energy_availability: RenewableAvailabilitySummary
    highest_demand_interval: DemandIntervalSummary
    lowest_demand_interval: DemandIntervalSummary
    grid_contract_demand_kw: float
    peak_demand_to_capacity_ratio_percent: float
    total_anomalies_count: int
    simulation_metadata: SimulationMetadata


class FactoryListItem(BaseModel):
    """Compact summary of a factory for list display."""
    factory_id: str
    name: str
    sector: str
    location: str
    total_rated_connected_power_kw: float
    grid_contract_demand_kw: float
    solar_capacity_kw: float
    wind_capacity_kw: float
    biomass_capacity_kw: float
    demo_scenario_description: str


class FactoryListResponse(BaseModel):
    """Response for GET /api/factories listing all configured demo factories."""
    total_factories: int
    factories: List[FactoryListItem]
    disclaimer: str = (
        "Fictional demonstration factories using synthetic data. Not actual customer facilities."
    )
